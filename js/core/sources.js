/**
 * Откуда берутся упражнения занятия.
 *
 * Адрес занятия — `#/drill/<ключ>`. Ключ говорит, что показывать:
 *
 *   g01, l02      — упражнения модуля;
 *   s01           — упражнения ситуации-письма;
 *   f1, f1-03     — клиника ошибок: семья или одна запись;
 *   review        — то, что пора повторить;
 *   mistakes      — то, на чём ошиблись в последний раз;
 *   test          — входной тест;
 *   tag:verb2     — всё по теме ошибки.
 */

import {
    модульПоId, ситуацияПоId, семьяПоId, записьОшибкиПоId, упражнениеПоId,
    упражненияДиагностики, упражненияПоТеме, всеУпражнения
} from '../data/catalog.js';
import { ТЕМЫ } from '../data/tags.js';
import { хранилище } from './store.js';
import { выбрать } from './session.js';

export const РАУНД = 10;
export const РАУНД_ПОВТОРА = 15;

/**
 * Возвращает { название, упражнения, режим, модуль } или null, если ключ
 * не знаком или упражнений нет.
 */
export function источник(ключ) {
    if (!ключ) return null;

    if (ключ === 'test') {
        const все = упражненияДиагностики();
        return все.length ? { название: 'Входной тест', упражнения: все, режим: 'диагностика', модуль: null, все: true } : null;
    }

    if (ключ === 'review') {
        const идут = хранилище.кПовторению().map(упражнениеПоId).filter(Boolean);
        return идут.length ? { название: 'Повторение', упражнения: идут, режим: 'повтор', модуль: null, число: РАУНД_ПОВТОРА } : null;
    }

    if (ключ === 'mistakes') {
        const ошибки = всеУпражнения().filter((у) => хранилище.последний(у.id) === false);
        return ошибки.length ? { название: 'Работа над ошибками', упражнения: ошибки, режим: 'повтор', модуль: null, число: РАУНД_ПОВТОРА } : null;
    }

    // Все упражнения модуля или ситуации подряд, без выборки в раунд. Нужен
    // и читателю («пройти всё»), и сквозной проверке, которой надо
    // перебрать каждое упражнение
    if (ключ.startsWith('all:')) {
        const и = источник(ключ.slice(4));
        return и ? { ...и, название: `${и.название}: все упражнения`, все: true, режим: 'раунд' } : null;
    }

    if (ключ.startsWith('tag:')) {
        const тема = ключ.slice(4);
        const список = упражненияПоТеме(тема);
        return список.length ? { название: ТЕМЫ[тема]?.title || тема, упражнения: список, режим: 'раунд', модуль: null } : null;
    }

    // Клиника ошибок: f1 — семья, f1-03 — одна запись
    if (/^f\d+$/.test(ключ)) {
        const с = семьяПоId(ключ);
        const список = с ? с.items.flatMap((э) => э.drills || []) : [];
        return список.length ? { название: с.title, упражнения: список, режим: 'раунд', модуль: null } : null;
    }

    if (/^f\d+-\d+$/.test(ключ)) {
        const н = записьОшибкиПоId(ключ);
        return н && н.запись.drills?.length ? { название: н.запись.title, упражнения: н.запись.drills, режим: 'раунд', модуль: null, все: true } : null;
    }

    const м = модульПоId(ключ);
    if (м) return { название: м.title, упражнения: м.exercises, режим: 'раунд', модуль: м.id };

    const с = ситуацияПоId(ключ);
    if (с) return { название: с.title, упражнения: с.drills || [], режим: 'раунд', модуль: null, все: true };

    return null;
}

/** Упражнения занятия: выбор из источника, если он больше раунда. */
export function собратьЗанятие(ключ) {
    const и = источник(ключ);
    if (!и || !и.упражнения.length) return null;

    const число = и.число || РАУНД;
    const упражнения = и.все ? и.упражнения : выбрать(и.упражнения, число);

    return { ...и, упражнения };
}
