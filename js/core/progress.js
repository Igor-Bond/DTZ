/**
 * Сводка прогресса: модули, письма, следующий шаг.
 *
 * Считается из хранилища и данных курса, ничего своего не хранит. Все
 * экраны спрашивают об успехах здесь — иначе главная страница и страница
 * прогресса показывали бы разные числа для одного и того же модуля.
 */

import { ГРАММАТИКА, СИТУАЦИИ } from '../data/catalog.js';
import { хранилище } from './store.js';

/** Доля освоенных упражнений, с которой модуль считается пройденным. */
export const ПОРОГ_МОДУЛЯ = 0.8;

export function прогрессМодуля(м) {
    const упр = м.exercises || [];
    const освоено = упр.filter((у) => хранилище.освоено(у.id)).length;
    const отвечено = упр.filter((у) => хранилище.упражнение(у.id)).length;
    const зап = хранилище.модуль(м.id);
    const доля = упр.length ? освоено / упр.length : 0;

    return {
        всего: упр.length,
        освоено,
        отвечено,
        доля,
        процент: Math.round(доля * 100),
        теория: зап.теория,
        мини: зап.мини,
        лучший: зап.лучший,
        раундов: зап.раундов,
        начат: зап.теория || отвечено > 0,
        пройден: зап.теория && доля >= ПОРОГ_МОДУЛЯ
    };
}

/**
 * Порядок модулей грамматики: по слабости из входного теста, если он пройден.
 * Без теста — по номерам. Модули, где тест показал 75 % и выше, не
 * пропускаются, а уходят в конец: теория всё равно полезна, но не срочна.
 */
export function порядокМодулей() {
    const д = хранилище.диагностика();
    if (!д) return [...ГРАММАТИКА];

    const слабость = (м) => {
        const р = д.модули[м.id];
        if (!р || !р.всего) return 0.5;
        return 1 - р.верно / р.всего;
    };

    return [...ГРАММАТИКА].sort((а, б) => {
        const сильныйА = слабость(а) <= 0.25 ? 1 : 0;
        const сильныйБ = слабость(б) <= 0.25 ? 1 : 0;
        if (сильныйА !== сильныйБ) return сильныйА - сильныйБ;
        return слабость(б) - слабость(а) || а.order - б.order;
    });
}

/** Итоги по письмам: сколько заданий написано и лучшая оценка. */
export function сводкаПисем() {
    const все = СИТУАЦИИ.flatMap((с) => с.tasks.map((з) => ({ ситуация: с, задание: з })));
    const написано = все.filter(({ задание }) => хранилище.письмо(задание.id).попыток > 0);
    const лучшая = написано.reduce((м, { задание }) => Math.max(м, хранилище.письмо(задание.id).итог), 0);

    return { всего: все.length, написано: написано.length, лучшая };
}

/** Что делать дальше: одна понятная подсказка для главной. */
export function следующийШаг() {
    if (!ГРАММАТИКА.length) return null;

    const д = хранилище.диагностика();
    const кПовтору = хранилище.кПовторению().length;

    if (!д) {
        return {
            заголовок: 'Начните с входного теста',
            подпись: 'Около 40 вопросов, 10–15 минут. Он покажет, какие темы сейчас слабее всего, и расставит модули по порядку.',
            кнопка: 'Пройти тест',
            href: '#/drill/test'
        };
    }

    if (кПовтору >= 10) {
        return {
            заголовок: `Пора повторить: ${кПовтору}`,
            подпись: 'Упражнения, которые вы делали раньше, вернулись по расписанию. Повторение закрепляет сильнее нового материала.',
            кнопка: 'Повторить',
            href: '#/drill/review'
        };
    }

    const порядок = порядокМодулей();
    const следующий = порядок.find((м) => !прогрессМодуля(м).пройден);

    if (следующий) {
        const п = прогрессМодуля(следующий);
        return {
            заголовок: `${следующий.order}. ${следующий.title}`,
            подпись: п.начат ? `Освоено ${п.освоено} из ${п.всего} упражнений.` : следующий.goal,
            кнопка: п.начат ? 'Продолжить' : 'Начать',
            href: п.теория ? `#/module/${следующий.id}` : `#/theory/${следующий.id}`
        };
    }

    const с = сводкаПисем();
    if (с.написано < с.всего) {
        return {
            заголовок: 'Пора писать письма',
            подпись: `Написано ${с.написано} из ${с.всего} заданий. Грамматика пройдена — теперь применяйте.`,
            кнопка: 'К письмам',
            href: '#/letters'
        };
    }

    return {
        заголовок: 'Сделайте пробу экзамена',
        подпись: '30 минут, два варианта на выбор, как на экзамене.',
        кнопка: 'Начать пробу',
        href: '#/exam'
    };
}
