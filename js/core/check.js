/**
 * Сверка ответов.
 *
 * Чистые функции без браузера и без состояния: их запускают и экран, и
 * валидатор содержимого в Node, и проверки. Всё, что решает «верно или нет»,
 * живёт здесь и больше нигде — иначе экран упражнения и разбор письма
 * разошлись бы в мелочах, а читатель увидел бы одну и ту же фразу то
 * правильной, то нет.
 *
 * Порядок строгости выбран по тому, что на экзамене стоит баллов:
 *   - слова, их порядок и окончания — строго;
 *   - заглавные у существительных — строго, это часть «Korrektheit», но
 *     первое слово предложения прощается: на клавиатуре телефона оно
 *     заглавное само, а на бумаге это уже привычка;
 *   - ä ö ü ß допускаются как ae oe ue ss, с напоминанием: русской раскладке
 *     умлаутов не хватает, а на экзамене писать придётся от руки;
 *   - запятые между словами — отдельным замечанием, а не провалом: смысл
 *     понятен, ошибка настоящая, но слово «неверно» тут слишком сильное;
 *   - точка в конце — не проверяется вовсе.
 */

export function почистить(текст) {
    return String(текст ?? '')
        .normalize('NFC')
        .replace(/[“”„«»]/g, '"')
        .replace(/[’‘´`]/g, "'")
        .replace(/[–—]/g, '-')
        .replace(/\s+/g, ' ')
        // «nicht,weil» и «nicht , weil» — одно и то же для читателя
        .replace(/\s+([,.;:!?])/g, '$1')
        .replace(/([,;:!?])(?=\p{L})/gu, '$1 ')
        .trim();
}

/** Слово без знаков по краям и знаки, что стояли после него. */
function слово(сырое) {
    const m = сырое.match(/^([^\p{L}\p{N}]*)(.*?)([^\p{L}\p{N}]*)$/u);
    return { текст: m[2], после: m[3] };
}

export function разложить(текст) {
    return почистить(текст)
        .split(' ')
        .filter(Boolean)
        .map(слово)
        .filter((с) => с.текст !== '');
}

const СКЛАДКИ = [['ä', 'ae'], ['ö', 'oe'], ['ü', 'ue'], ['Ä', 'Ae'], ['Ö', 'Oe'], ['Ü', 'Ue'], ['ß', 'ss']];

/** Слово в записи без умлаутов: «schön» и «schoen» становятся равны. */
function сложить(слово) {
    let r = слово;
    for (const [с, замена] of СКЛАДКИ) r = r.split(с).join(замена);
    return r;
}

/**
 * Сравнение двух слов.
 * Возвращает 'точно', 'умлаут', 'регистр' или null.
 */
function сравнитьСлово(ввод, эталон, первое) {
    if (ввод === эталон) return 'точно';

    if (ввод.toLowerCase() === эталон.toLowerCase()) return первое ? 'точно' : 'регистр';

    if (сложить(ввод) === сложить(эталон)) return 'умлаут';
    if (сложить(ввод).toLowerCase() === сложить(эталон).toLowerCase()) return первое ? 'умлаут' : 'регистр';

    return null;
}

/** Результат по умолчанию: не совпало. */
const МИМО = Object.freeze({ ok: false, замечания: [], почти: null });

function сравнитьПредложения(ввод, эталон) {
    if (ввод.length !== эталон.length) return МИМО;

    const замечания = new Set();
    let регистр = false;

    for (let i = 0; i < ввод.length; i++) {
        const с = сравнитьСлово(ввод[i].текст, эталон[i].текст, i === 0);

        if (!с) return МИМО;
        if (с === 'умлаут') замечания.add('умлаут');
        if (с === 'регистр') регистр = true;

        // Последняя пара — конец предложения: точка там не проверяется.
        // А вот запятая внутри — да
        if (i < ввод.length - 1) {
            if (ввод[i].после.includes(',') !== эталон[i].после.includes(',')) {
                замечания.add('запятая');
            }
        }
    }

    if (регистр) return { ok: false, замечания: [], почти: 'регистр' };

    return { ok: true, замечания: [...замечания], почти: null };
}

/**
 * Ответ целым предложением против списка допустимых.
 * Из нескольких подходящих берёт тот, что без замечаний.
 */
export function сверитьПредложение(ввод, допустимые) {
    const х = разложить(ввод);
    if (!х.length) return МИМО;

    let лучшее = МИМО;

    for (const вариант of допустимые) {
        const р = сравнитьПредложения(х, разложить(вариант));

        if (р.ok && !р.замечания.length) return р;
        if (р.ok && !лучшее.ok) лучшее = р;
        if (!р.ok && р.почти && !лучшее.ok && !лучшее.почти) лучшее = р;
    }

    return лучшее;
}

/**
 * Один пропуск: слово или короткое сочетание.
 * `началоПредложения` прощает регистр первой буквы.
 */
export function сверитьПропуск(ввод, допустимые, началоПредложения = false) {
    const х = почистить(ввод);
    if (!х) return МИМО;

    let лучшее = МИМО;

    for (const вариант of допустимые) {
        const э = почистить(вариант);
        const с = сравнитьСлово(х, э, началоПредложения);

        if (с === 'точно') return { ok: true, замечания: [], почти: null };
        if (с === 'умлаут') лучшее = { ok: true, замечания: ['умлаут'], почти: null };
        if (с === 'регистр' && !лучшее.ok) лучшее = { ok: false, замечания: [], почти: 'регистр' };
    }

    return лучшее;
}

/**
 * Собранное из плашек. Регистр не сравнивается: плашки дают его сами, и
 * менять его читателю нечем — проверять тут нечего.
 */
export function сверитьСборку(слова, допустимые) {
    // Конечный знак предложения плашки не несут, поэтому его не сравнивают
    const нормально = (с) => почистить(с).toLowerCase().replace(/[.!?]+$/, '');
    const х = нормально(слова.join(' '));
    return допустимые.some((в) => нормально(в) === х);
}

/** Сколько слов в тексте — как считает экзамен: всё, что содержит букву или цифру. */
export function сколькоСлов(текст) {
    return почистить(текст).split(' ').filter((с) => /[\p{L}\p{N}]/u.test(с)).length;
}

/** Вставляет ответы вместо пропусков — получается готовое предложение. */
export function заполнить(текст, ответы) {
    let i = 0;
    return текст.replace(/___/g, () => {
        const а = ответы[i++];
        return Array.isArray(а) ? а[0] : а;
    });
}

