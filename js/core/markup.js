/**
 * Разметка внутри строк содержимого.
 *
 * Две вещи: **жирное** и `немецкий фрагмент`. Всё остальное — обычный
 * текст. Экранирование выполняется первым: содержимое пишут люди и помощники,
 * и угловая скобка в тексте не должна ломать страницу.
 *
 * Результат помечен как готовая разметка, поэтому шаблоны ui.html вставляют
 * его как есть.
 */

import { ui } from './ui.js';

function преобразовать(строка) {
    return ui.esc(строка)
        .replace(/`([^`]+)`/g, '<span class="de">$1</span>')
        .replace(/\*\*(.+?)\*\*/g, '<b>$1</b>');
}

/** Русский текст с вкраплениями немецкого и выделениями. */
export function разметка(строка) {
    return ui.raw(преобразовать(String(строка ?? '')));
}

/** Целиком немецкая строка: выделения допустимы, обратных кавычек нет. */
export function немецкий(строка) {
    return ui.raw(ui.esc(String(строка ?? '')).replace(/\*\*(.+?)\*\*/g, '<b>$1</b>'));
}

/** Строка без разметки — для поиска и для печати простым текстом. */
export function безРазметки(строка) {
    return String(строка ?? '').replace(/\*\*/g, '').replace(/`/g, '');
}
