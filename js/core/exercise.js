/**
 * Упражнение: как его показать и как проверить ответ.
 *
 * Данные упражнений — обычные объекты из js/data (их формат описан в
 * docs/CONTENT.md). Здесь нет разметки и нет хранилища: на входе упражнение
 * и ответ читателя, на выходе — решение и то, что показать. Поэтому всё
 * проверяется в Node и в браузере одинаково.
 *
 * Ответ у каждого типа свой:
 *   choice — индекс варианта в исходном списке `options`;
 *   gap    — массив строк, по одной на пропуск;
 *   build  — массив выбранных слов в порядке выбора;
 *   order  — массив частей в порядке, выбранном читателем;
 *   fix, join, translate — строка.
 */

import {
    сверитьПредложение, сверитьПропуск, сверитьСборку, заполнить, разложить, почистить
} from './check.js';

/** Перемешивание Фишера — Йетса; `случайное` подменяется в проверках. */
export function перемешать(список, случайное = Math.random) {
    const р = [...список];

    for (let i = р.length - 1; i > 0; i--) {
        const j = Math.floor(случайное() * (i + 1));
        [р[i], р[j]] = [р[j], р[i]];
    }

    return р;
}

/**
 * Перемешивание, при котором порядок точно отличается от исходного.
 * Для двух-трёх слов случайность могла бы вернуть исходный порядок, и
 * задание «составьте предложение» оказалось бы уже решённым.
 */
function перемешатьИначе(список, случайное) {
    if (список.length < 2) return [...список];

    for (let попытка = 0; попытка < 12; попытка++) {
        const р = перемешать(список, случайное);
        if (р.some((х, i) => х !== список[i])) return р;
    }

    // Крайний случай (все элементы равны): циклический сдвиг
    return [...список.slice(1), список[0]];
}

/**
 * Карточка — упражнение, готовое к показу: варианты перемешаны, плашки
 * нарезаны. Перемешивание происходит один раз, при подготовке: перерисовка
 * экрана не должна менять порядок под пальцем.
 */
export function подготовить(у, случайное = Math.random) {
    switch (у.type) {
        case 'choice': {
            const номера = у.options.map((_, i) => i);
            return { ...у, порядок: перемешать(номера, случайное) };
        }

        case 'build': {
            // `extra` — лишние слова-ловушки: в ответ они не входят, но лежат на столе
            const слова = [...(у.words ? у.words.map(безКонечногоЗнака) : разложитьПлашки(у.answer[0])), ...(у.extra || [])];
            const плашки = слова.map((текст, i) => ({ id: i, текст }));
            return { ...у, плашки: перемешатьИначе(плашки, случайное) };
        }

        case 'order': {
            const части = у.items.map((текст, i) => ({ id: i, текст }));
            return { ...у, плашки: перемешатьИначе(части, случайное) };
        }

        default:
            return { ...у };
    }
}

/**
 * Плашки из готового предложения: слова с приклеенными запятыми, без
 * конечной точки.
 *
 * Запятая — часть слова: читатель видит, куда она ставится, и учится на
 * этом. А точка в конце — нет: предложение с другим порядком слов
 * заканчивается другим словом, и приклеенная к нему точка сделала бы такой
 * вариант несобираемым из плашек.
 */
export function разложитьПлашки(предложение) {
    const слова = почистить(предложение).split(' ').filter(Boolean);

    // Только у последнего слова: точка у «20.» в середине — часть порядкового числа
    if (слова.length) слова[слова.length - 1] = слова[слова.length - 1].replace(/[.!?]+$/, '');

    return слова;
}

/** Знак в конце явно заданной плашки: срезается, если это не точка порядкового числа. */
const безКонечногоЗнака = (с) => с.replace(/(?<!\d)[.!?]+$/, '');

/** Пропуск начинает предложение: тогда регистр первой буквы прощается. */
function началоПредложения(текст, номерПропуска) {
    let позиция = -1;

    for (let k = 0; k <= номерПропуска; k++) {
        позиция = текст.indexOf('___', позиция + 1);
    }

    const до = текст.slice(0, позиция).trimEnd();
    return до === '' || /[.!?]$/.test(до);
}

/**
 * Проверка ответа.
 * Возвращает { ok, замечания, почти, правильно, варианты, пропуски }:
 *   ok         — верно ли;
 *   замечания  — что отметить при верном ответе (запятая, умлаут);
 *   почти      — 'регистр', если слова верны, а заглавные нет;
 *   правильно  — как правильно (для показа);
 *   варианты   — другие верные варианты;
 *   пропуски   — у gap: что с каждым пропуском.
 */
export function проверить(у, ответ) {
    switch (у.type) {
        case 'choice': {
            const ok = ответ === у.answer;
            return { ok, замечания: [], почти: null, правильно: у.options[у.answer], варианты: [] };
        }

        case 'gap': {
            const допустимые = у.answer.map((а) => (Array.isArray(а) ? а : [а]));
            const пропуски = допустимые.map((д, k) => {
                const ввод = ответ?.[k] ?? '';
                return { ...сверитьПропуск(ввод, д, началоПредложения(у.text, k)), ввод, ожидалось: д[0] };
            });

            const ok = пропуски.every((п) => п.ok);
            const замечания = [...new Set(пропуски.flatMap((п) => п.замечания))];
            const почти = !ok && пропуски.some((п) => п.почти) && пропуски.every((п) => п.ok || п.почти) ? 'регистр' : null;

            return {
                ok,
                замечания: ok ? замечания : [],
                почти,
                правильно: заполнить(у.text, допустимые),
                варианты: [],
                пропуски
            };
        }

        case 'build': {
            const ok = сверитьСборку(ответ || [], у.answer);
            return { ok, замечания: [], почти: null, правильно: у.answer[0], варианты: у.answer.slice(1) };
        }

        case 'order': {
            const ok = Array.isArray(ответ) && ответ.length === у.items.length && ответ.every((х, i) => х === у.items[i]);
            return { ok, замечания: [], почти: null, правильно: у.items.join('\n'), варианты: [] };
        }

        case 'fix':
        case 'join':
        case 'translate': {
            const р = сверитьПредложение(ответ || '', у.answer);
            return {
                ok: р.ok,
                замечания: р.ok ? р.замечания : [],
                почти: р.почти,
                правильно: у.answer[0],
                варианты: у.answer.slice(1)
            };
        }

        default:
            throw new Error(`Неизвестный тип упражнения: ${у.type}`);
    }
}

/** Как правильно — строкой, для списка ошибок в итоге. */
export function правильныйОтвет(у) {
    const пустой = { choice: -1, gap: [], build: [], order: [], fix: '', join: '', translate: '' }[у.type];
    return проверить(у, пустой).правильно;
}

/** Можно ли «засчитать мой вариант»: только там, где ответ — свободный текст. */
export function можноЗасчитать(у) {
    return у.type === 'fix' || у.type === 'join' || у.type === 'translate';
}

/** Сколько слов в ответе — для подсказки о слишком коротком вводе. */
export function словВвода(текст) {
    return разложить(текст).length;
}
