/**
 * Делегирование событий.
 *
 * Разметка собирается строками и перерисовывается целиком, поэтому вешать
 * addEventListener на каждый элемент бессмысленно — после перерисовки
 * слушатели теряются вместе с узлами. Вместо этого элемент объявляет
 * намерение атрибутом:
 *
 *   <button data-action="выбрать" data-i="2">ответ</button>
 *
 * а обработчик регистрируется один раз на всё приложение. Inline-обработчики
 * onclick при этом не нужны, и модули не приходится выкладывать в window.
 */

let запущено = false;

const нажатия = new Map();
const изменения = new Map();

let наОшибку = null;

function сообщить(имя, ошибка) {
    console.error(`[Действия] Ошибка в обработчике «${имя}»:`, ошибка);

    try {
        наОшибку?.(ошибка, имя);
    } catch (e) {
        console.error('[Действия] Ошибка в сообщении об ошибке:', e);
    }
}

function раздать(карта, событие, атрибут) {
    // Событие может прийти не от элемента (например, от document в проверках)
    const el = событие.target?.closest?.(`[${атрибут}]`);
    if (!el) return;

    const имя = el.getAttribute(атрибут);
    const обработчик = карта.get(имя);

    if (!обработчик) {
        console.warn(`[Действия] Нет обработчика «${имя}»`);
        return;
    }

    /*
     * Обычный try не ловит отказ асинхронного обработчика: он уходит в
     * необработанное обещание и не доходит никуда. Для тренажёра это значит
     * нажатую кнопку, после которой ничего не произошло, — ребёнок решит,
     * что промахнулся, и будет жать снова.
     */
    Promise.resolve()
        .then(() => обработчик(el, событие))
        .catch((e) => сообщить(имя, e));
}

export const actions = {

    on(имя, обработчик) {
        нажатия.set(имя, обработчик);
    },

    onChange(имя, обработчик) {
        изменения.set(имя, обработчик);
    },

    /**
     * Имена, на которые кто-то подписан, — для проверки.
     *
     * Кнопка с именем, которого никто не слушает, нажимается и молчит: с
     * виду живая, а не делает ничего. Найти такую можно только сверив
     * разметку с этим списком.
     */
    names() {
        return { click: [...нажатия.keys()], change: [...изменения.keys()] };
    },

    onError(обратный) {
        наОшибку = обратный;
    },

    init() {
        // Повторный вызов навесил бы вторые слушатели, и каждый ответ
        // засчитался бы дважды
        if (запущено) return;
        запущено = true;

        document.addEventListener('click', (e) => раздать(нажатия, e, 'data-action'));
        document.addEventListener('change', (e) => раздать(изменения, e, 'data-change'));
    }
};
