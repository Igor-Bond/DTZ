/**
 * Занятие: очередь упражнений, ответы, итог.
 *
 * Состояние живёт в памяти модуля, а не в localStorage: занятие длится минуты,
 * и перезагрузка посреди него — не повод хранить полупройденный раунд. А вот
 * результат каждого ответа записывается в хранилище сразу: ошибка, сделанная
 * за минуту до закрытия вкладки, всё равно должна вернуться в повторение.
 *
 * Запись происходит на шаге «дальше», а не на шаге «проверить»: между ними
 * читатель может нажать «мой вариант тоже верен», и ответ из неверного
 * превращается в верный. Записать раньше значило бы отметить ошибку, которой
 * не было.
 */

import { подготовить, проверить, перемешать } from './exercise.js';
import { хранилище } from './store.js';

let ТЕКУЩАЯ = null;

const ПО_УМОЛЧАНИЮ = 10;

/**
 * Выбор упражнений в раунд.
 *
 * Сначала то, что ещё не отвечено или отвечено неверно; потом то, что в
 * нижних ящиках; остальное — по кругу. Внутри каждой группы порядок
 * случайный, а итоговый — перемешан: подряд идущие упражнения одного типа
 * утомляют и приучают отвечать на автомате.
 */
export function выбрать(упражнения, число = ПО_УМОЛЧАНИЮ, случайное = Math.random) {
    const вес = (у) => {
        const з = хранилище.упражнение(у.id);
        if (!з) return 0;
        if (!з.последний) return 1;
        return 2 + з.ящик;
    };

    const группы = new Map();
    for (const у of упражнения) {
        const в = вес(у);
        if (!группы.has(в)) группы.set(в, []);
        группы.get(в).push(у);
    }

    const порядок = [...группы.keys()].sort((а, б) => а - б);
    const выбранные = [];

    for (const в of порядок) {
        for (const у of перемешать(группы.get(в), случайное)) {
            if (выбранные.length >= число) break;
            выбранные.push(у);
        }
        if (выбранные.length >= число) break;
    }

    return перемешать(выбранные, случайное);
}

export const сессия = {

    /**
     * Начинает занятие.
     * `упражнения` уже выбраны; `опции.режим` — 'раунд' | 'повтор' | 'диагностика'.
     */
    начать(ключ, название, упражнения, опции = {}) {
        ТЕКУЩАЯ = {
            ключ,
            название,
            режим: опции.режим || 'раунд',
            модуль: опции.модуль || null,
            очередь: упражнения.map((у) => подготовить(у)),
            i: 0,
            стадия: 'вопрос',      // 'вопрос' → 'ответ'
            ввод: null,
            результат: null,
            засчитано: false,
            записи: [],            // { id, ok, тема }
            ошибки: [],            // упражнения (исходные), которые не удались
            закончено: false
        };

        return ТЕКУЩАЯ;
    },

    текущая() {
        return ТЕКУЩАЯ;
    },

    сбросить() {
        ТЕКУЩАЯ = null;
    },

    есть(ключ) {
        return !!ТЕКУЩАЯ && ТЕКУЩАЯ.ключ === ключ && !ТЕКУЩАЯ.закончено;
    },

    карточка() {
        return ТЕКУЩАЯ ? ТЕКУЩАЯ.очередь[ТЕКУЩАЯ.i] : null;
    },

    номер() {
        return ТЕКУЩАЯ ? ТЕКУЩАЯ.i + 1 : 0;
    },

    всего() {
        return ТЕКУЩАЯ ? ТЕКУЩАЯ.очередь.length : 0;
    },

    /** Проверка ответа. Ничего не пишет в хранилище — это делает `дальше`. */
    ответить(ввод) {
        const с = ТЕКУЩАЯ;
        if (!с || с.стадия !== 'вопрос') return null;

        с.ввод = ввод;
        с.результат = проверить(с.очередь[с.i], ввод);
        с.засчитано = false;
        с.стадия = 'ответ';

        return с.результат;
    },

    /** «Мой вариант тоже верный»: ответ считается верным. */
    засчитатьМой() {
        const с = ТЕКУЩАЯ;
        if (!с || с.стадия !== 'ответ' || с.результат.ok) return;
        с.засчитано = true;
    },

    верноСейчас() {
        const с = ТЕКУЩАЯ;
        return !!(с && с.результат && (с.результат.ok || с.засчитано));
    },

    /**
     * Следующее упражнение. Записывает результат текущего.
     * Возвращает true, пока занятие не закончилось.
     */
    дальше() {
        const с = ТЕКУЩАЯ;
        if (!с || с.стадия !== 'ответ') return !!с && !с.закончено;

        const у = с.очередь[с.i];
        const ok = с.результат.ok || с.засчитано;

        хранилище.записатьОтвет(у.id, ok, у.tag);
        с.записи.push({ id: у.id, ok, тема: у.tag });
        if (!ok) с.ошибки.push(у);

        с.i += 1;
        с.стадия = 'вопрос';
        с.ввод = null;
        с.результат = null;
        с.засчитано = false;

        if (с.i >= с.очередь.length) {
            с.закончено = true;
            с.итог = итог(с);
            // Процент модуля записывается один раз, в конце раунда
            if (с.режим === 'раунд' && с.модуль) хранилище.записатьРаунд(с.модуль, с.итог.процент);

            // Входной тест: итог по модулям нужен главной странице для маршрута
            if (с.режим === 'диагностика') {
                хранилище.записатьДиагностику({ модули: с.итог.модули, всего: с.итог.всего, верно: с.итог.верных });
            }
            return false;
        }

        return true;
    }
};

function итог(с) {
    const верных = с.записи.filter((з) => з.ok).length;
    const всего = с.записи.length;

    // По темам: чтобы показать, где именно спотыкались
    const темы = {};
    for (const з of с.записи) {
        const т = темы[з.тема] || { верно: 0, ошибок: 0 };
        if (з.ok) т.верно += 1; else т.ошибок += 1;
        темы[з.тема] = т;
    }

    // По модулям: id упражнения начинается с id модуля до первого дефиса
    const модули = {};
    for (const з of с.записи) {
        const м = з.id.split('-')[0];
        const р = модули[м] || { верно: 0, всего: 0 };
        р.всего += 1;
        if (з.ok) р.верно += 1;
        модули[м] = р;
    }

    return {
        верных,
        всего,
        процент: всего ? Math.round((верных / всего) * 100) : 0,
        темы,
        модули,
        ошибки: с.ошибки.map((у) => у.id)
    };
}
