/**
 * Lesen: проверка ответов и подсчёт баллов.
 *
 * Чистая логика, без разметки и хранилища. Формат ответов:
 *   Teil 1, mc в Teil 3, Teil 5 — индекс варианта 0, 1, 2;
 *   Teil 2                      — буква объявления 'a'…'h' или 'x';
 *   rf (Teil 3 и 4)             — true для richtig, false для falsch.
 * Неотвеченный вопрос — отсутствие ключа в объекте ответов: он не равен
 * ни одному верному ответу, и «false» (falsch) от «не отвечено» отличается.
 */

import { ЗАДАНИЙ_В_ЧАСТИ, МИНУТ_LESEN, ВСЕГО_ЗАДАНИЙ_LESEN } from '../data/catalog.js';
import { ui } from './ui.js';

export { ЗАДАНИЙ_В_ЧАСТИ, МИНУТ_LESEN, ВСЕГО_ЗАДАНИЙ_LESEN };

/**
 * Ориентир B1 для одного Lesen. В экзамене Hören и Lesen считаются вместе:
 * 33 правильных из 45 — B1, 20 — A2. Пропорция даёт для 25 заданий около
 * 18,3, то есть уверенный B1 начинается с 19 баллов.
 */
export const ПОРОГ_B1 = 19;
export const ПОРОГ_A2 = 11;

export function верно(задание, ответ) {
    if (ответ === undefined || ответ === null) return false;
    return ответ === задание.answer;
}

/** Результат набора: { баллов, всего, ответили, подробно: [{ id, верно, ответ, правильный }] }. */
export function оценитьНабор(набор, ответы) {
    const подробно = набор.items.map((п) => ({
        id: п.id,
        верно: верно(п, ответы[п.id]),
        ответ: ответы[п.id],
        правильный: п.answer
    }));

    return {
        баллов: подробно.filter((х) => х.верно).length,
        всего: набор.items.length,
        ответили: подробно.filter((х) => х.ответ !== undefined).length,
        подробно
    };
}

/** Подпись вердикта по сумме баллов пробы: уровень и пояснение. */
export function вердиктПробы(баллов) {
    if (баллов >= ПОРОГ_B1) return { уровень: 'b1', подпись: 'Уровень B1', пояснение: `ориентир — ${ПОРОГ_B1} из 25 и выше` };
    if (баллов >= ПОРОГ_A2) return { уровень: 'a2', подпись: 'Уровень A2', пояснение: `до B1 не хватает ${ПОРОГ_B1 - баллов}` };
    return { уровень: 'low', подпись: 'Ниже A2', пояснение: 'начните со стратегии по частям и с Teil 1–2' };
}

/**
 * Текст с подсветкой фрагментов-подсказок.
 * Возвращает готовую разметку: всё экранируется, найденные фрагменты
 * оборачиваются в <mark>. Каждый фрагмент подсвечивается при первом
 * вхождении; пересечения пропускаются.
 */
export function выделить(текст, фрагменты = []) {
    const строка = String(текст ?? '');
    const найденные = [];

    for (const ф of фрагменты) {
        if (!ф) continue;
        const от = строка.indexOf(ф);
        if (от >= 0) найденные.push({ от, до: от + ф.length });
    }

    найденные.sort((а, б) => а.от - б.от);

    const куски = [];
    let позиция = 0;

    for (const н of найденные) {
        if (н.от < позиция) continue;
        куски.push(ui.esc(строка.slice(позиция, н.от)));
        куски.push(`<mark>${ui.esc(строка.slice(н.от, н.до))}</mark>`);
        позиция = н.до;
    }

    куски.push(ui.esc(строка.slice(позиция)));
    return ui.raw(куски.join(''));
}

/** Буквы вариантов a, b, c. */
export const БУКВЫ = ['a', 'b', 'c'];
export const ОБЪЯВЛЕНИЯ = ['a', 'b', 'c', 'd', 'e', 'f', 'g', 'h'];

/** Как показать ответ читателя или верный ответ строкой. */
export function подписьОтвета(задание, часть, значение) {
    if (значение === undefined || значение === null) return '—';
    if (часть === 2) return значение === 'x' ? 'x — нет подходящего объявления' : `объявление ${значение}`;
    if (typeof значение === 'boolean') return значение ? 'richtig' : 'falsch';
    if (Array.isArray(задание.options)) return `${БУКВЫ[значение]}) ${задание.options[значение]}`;
    return String(значение);
}
