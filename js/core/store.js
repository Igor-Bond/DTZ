/**
 * Прогресс — в localStorage.
 *
 * Не IndexedDB: данные небольшие (ящики упражнений, черновики писем, оценки),
 * и база с версиями схемы здесь дороже задачи. Синхронизации между
 * устройствами нет намеренно; вместо неё — выгрузка и загрузка файлом: так
 * прогресс можно перенести с компьютера на телефон без учётной записи.
 *
 * Отказ хранилища не должен ронять занятие. В приватном окне localStorage
 * бросает исключение на любом обращении; тогда всё работает как обычно, но
 * результаты забываются при закрытии.
 */

/**
 * Ключ хранения подменяется проверками: они гоняют настоящее хранилище и без
 * подмены стёрли бы прогресс на том же устройстве.
 */
const КЛЮЧ = globalThis.__BRIEFE_KEY__ || 'briefe.v1';

const СУТКИ = 24 * 60 * 60 * 1000;

/**
 * Интервалы ящиков. Ящик 0 — ошибка или первый раз: вернуть скоро. Дальше
 * каждый верный ответ сдвигает упражнение в следующий ящик, неверный —
 * возвращает в нулевой.
 */
export const ИНТЕРВАЛЫ = [0, 1 * СУТКИ, 3 * СУТКИ, 7 * СУТКИ, 21 * СУТКИ];
export const ПОСЛЕДНИЙ_ЯЩИК = ИНТЕРВАЛЫ.length - 1;

function пусто() {
    return {
        версия: 1,
        упр: {},
        модули: {},
        диагностика: null,
        письма: {},
        пробы: [],
        фразы: {},
        темы: {}
    };
}

let вПамяти = null;

function прочитатьСырое() {
    try {
        const текст = localStorage.getItem(КЛЮЧ);
        return текст ? JSON.parse(текст) : null;
    } catch {
        return null;
    }
}

/**
 * Чужое или испорченное содержимое не должно ломать запуск: ключ может
 * пережить смену версии или оказаться вовсе чужим — адрес один на все
 * страницы домена. Поэтому не доверяем ничему и берём только знакомые поля.
 */
function привести(данные) {
    const р = пусто();
    if (!данные || typeof данные !== 'object') return р;

    const объект = (в) => (в && typeof в === 'object' && !Array.isArray(в) ? в : {});

    for (const [id, у] of Object.entries(объект(данные.упр))) {
        if (!у || typeof у !== 'object') continue;
        р.упр[id] = {
            верно: Number(у.верно) || 0,
            ошибок: Number(у.ошибок) || 0,
            ящик: Math.min(ПОСЛЕДНИЙ_ЯЩИК, Math.max(0, Number(у.ящик) || 0)),
            срок: Number(у.срок) || 0,
            посл: Number(у.посл) || 0,
            последний: у.последний === true
        };
    }

    for (const [id, м] of Object.entries(объект(данные.модули))) {
        if (!м || typeof м !== 'object') continue;
        р.модули[id] = {
            теория: м.теория === true,
            раундов: Number(м.раундов) || 0,
            лучший: Math.max(0, Math.min(100, Number(м.лучший) || 0)),
            мини: м.мини === true,
            когда: Number(м.когда) || 0
        };
    }

    if (данные.диагностика && typeof данные.диагностика === 'object') {
        const д = данные.диагностика;
        р.диагностика = {
            когда: Number(д.когда) || 0,
            модули: объект(д.модули),
            всего: Number(д.всего) || 0,
            верно: Number(д.верно) || 0
        };
    }

    for (const [id, п] of Object.entries(объект(данные.письма))) {
        if (!п || typeof п !== 'object') continue;
        р.письма[id] = {
            черновик: typeof п.черновик === 'string' ? п.черновик : '',
            оценки: объект(п.оценки),
            итог: Number(п.итог) || 0,
            слов: Number(п.слов) || 0,
            попыток: Number(п.попыток) || 0,
            когда: Number(п.когда) || 0
        };
    }

    if (Array.isArray(данные.пробы)) {
        р.пробы = данные.пробы
            .filter((п) => п && typeof п === 'object')
            .map((п) => ({
                когда: Number(п.когда) || 0,
                задание: String(п.задание || ''),
                слов: Number(п.слов) || 0,
                итог: Number(п.итог) || 0,
                оценки: объект(п.оценки),
                минут: Number(п.минут) || 0
            }))
            .slice(-100);
    }

    for (const [id, ф] of Object.entries(объект(данные.фразы))) {
        if (!ф || typeof ф !== 'object') continue;
        р.фразы[id] = {
            ящик: Math.min(ПОСЛЕДНИЙ_ЯЩИК, Math.max(0, Number(ф.ящик) || 0)),
            срок: Number(ф.срок) || 0
        };
    }

    for (const [тема, н] of Object.entries(объект(данные.темы))) {
        if (typeof н === 'object' && н) {
            р.темы[тема] = { верно: Number(н.верно) || 0, ошибок: Number(н.ошибок) || 0 };
        }
    }

    return р;
}

function прочитать() {
    if (вПамяти) return вПамяти;
    return привести(прочитатьСырое());
}

function записать(данные) {
    try {
        localStorage.setItem(КЛЮЧ, JSON.stringify(данные));
        вПамяти = null;
    } catch {
        вПамяти = данные;
    }

    return данные;
}

/** Изменение: прочитать, изменить, записать. Возвращает то, что вернул `изменить`. */
function менять(изменить) {
    const данные = прочитать();
    const результат = изменить(данные);
    записать(данные);
    return результат;
}

export const хранилище = {

    всё() {
        return прочитать();
    },

    // ---------------- упражнения и ящики ----------------

    упражнение(id) {
        return прочитать().упр[id] || null;
    },

    /**
     * Результат ответа. Верный сдвигает упражнение в следующий ящик, неверный
     * возвращает в нулевой и просит повторить сразу же в следующем
     * повторении.
     */
    записатьОтвет(id, верно, тема, сейчас = Date.now()) {
        return менять((д) => {
            const у = д.упр[id] || { верно: 0, ошибок: 0, ящик: 0, срок: 0, посл: 0, последний: false };

            if (верно) {
                у.верно += 1;
                у.ящик = Math.min(ПОСЛЕДНИЙ_ЯЩИК, у.ящик + 1);
            } else {
                у.ошибок += 1;
                у.ящик = 0;
            }

            у.последний = !!верно;
            у.посл = сейчас;
            у.срок = сейчас + ИНТЕРВАЛЫ[у.ящик];
            д.упр[id] = у;

            if (тема) {
                const т = д.темы[тема] || { верно: 0, ошибок: 0 };
                if (верно) т.верно += 1; else т.ошибок += 1;
                д.темы[тема] = т;
            }

            return у;
        });
    },

    /** Какие упражнения пора повторить: отвеченные, у которых срок вышел. */
    кПовторению(сейчас = Date.now()) {
        const д = прочитать();
        return Object.entries(д.упр)
            .filter(([, у]) => у.срок <= сейчас && (!у.последний || у.ящик < ПОСЛЕДНИЙ_ЯЩИК))
            .sort((а, б) => а[1].срок - б[1].срок)
            .map(([id]) => id);
    },

    /** Освоено ли упражнение: последний ответ верен, и он не первый. */
    освоено(id) {
        const у = прочитать().упр[id];
        return !!(у && у.последний && у.ящик >= 2);
    },

    /** Верно ли ответили в последний раз. */
    последний(id) {
        const у = прочитать().упр[id];
        return у ? у.последний : null;
    },

    // ---------------- модули ----------------

    модуль(id) {
        return прочитать().модули[id] || { теория: false, раундов: 0, лучший: 0, мини: false, когда: 0 };
    },

    отметитьТеорию(id) {
        менять((д) => {
            const м = д.модули[id] || { теория: false, раундов: 0, лучший: 0, мини: false, когда: 0 };
            м.теория = true;
            м.когда = Date.now();
            д.модули[id] = м;
        });
    },

    отметитьМини(id, сделано = true) {
        менять((д) => {
            const м = д.модули[id] || { теория: false, раундов: 0, лучший: 0, мини: false, когда: 0 };
            м.мини = !!сделано;
            д.модули[id] = м;
        });
    },

    /** Итог раунда: процент только растёт — так же, как лучший результат. */
    записатьРаунд(id, процент) {
        менять((д) => {
            const м = д.модули[id] || { теория: false, раундов: 0, лучший: 0, мини: false, когда: 0 };
            м.раундов += 1;
            м.лучший = Math.max(м.лучший, Math.round(процент));
            м.когда = Date.now();
            д.модули[id] = м;
        });
    },

    // ---------------- входной тест ----------------

    диагностика() {
        return прочитать().диагностика;
    },

    записатьДиагностику(итог) {
        менять((д) => {
            д.диагностика = { когда: Date.now(), модули: итог.модули, всего: итог.всего, верно: итог.верно };
        });
    },

    // ---------------- письма ----------------

    письмо(id) {
        return прочитать().письма[id] || { черновик: '', оценки: {}, итог: 0, слов: 0, попыток: 0, когда: 0 };
    },

    сохранитьЧерновик(id, текст) {
        менять((д) => {
            const п = д.письма[id] || { черновик: '', оценки: {}, итог: 0, слов: 0, попыток: 0, когда: 0 };
            п.черновик = String(текст);
            п.когда = Date.now();
            д.письма[id] = п;
        });
    },

    /** Самооценка по четырём критериям: оценки 0–5, итог из 20. */
    записатьОценкуПисьма(id, оценки, слов) {
        return менять((д) => {
            const п = д.письма[id] || { черновик: '', оценки: {}, итог: 0, слов: 0, попыток: 0, когда: 0 };
            const итог = Object.values(оценки).reduce((а, б) => а + (Number(б) || 0), 0);

            п.оценки = { ...оценки };
            п.итог = итог;
            п.слов = слов;
            п.попыток += 1;
            п.когда = Date.now();
            д.письма[id] = п;
            return итог;
        });
    },

    записатьПробу(проба) {
        менять((д) => {
            д.пробы.push({
                когда: Date.now(),
                задание: проба.задание,
                слов: проба.слов,
                итог: проба.итог,
                оценки: проба.оценки || {},
                минут: проба.минут || 0
            });
            д.пробы = д.пробы.slice(-100);
        });
    },

    // ---------------- фразы ----------------

    фраза(ключ) {
        return прочитать().фразы[ключ] || null;
    },

    записатьФразу(ключ, знал, сейчас = Date.now()) {
        менять((д) => {
            const ф = д.фразы[ключ] || { ящик: 0, срок: 0 };
            ф.ящик = знал ? Math.min(ПОСЛЕДНИЙ_ЯЩИК, ф.ящик + 1) : 0;
            ф.срок = сейчас + ИНТЕРВАЛЫ[ф.ящик];
            д.фразы[ключ] = ф;
        });
    },

    // ---------------- перенос и сброс ----------------

    выгрузить() {
        return JSON.stringify({ приложение: 'briefe', ...прочитать() }, null, 1);
    },

    /** Загрузка из файла: чужое отбрасывается, `привести` берёт только знакомое. */
    загрузить(текст) {
        let сырое;
        try {
            сырое = JSON.parse(текст);
        } catch {
            throw new Error('Это не файл прогресса: не удалось прочитать.');
        }

        if (!сырое || typeof сырое !== 'object' || сырое.приложение !== 'briefe') {
            throw new Error('Это не файл прогресса «Briefe».');
        }

        записать(привести(сырое));
    },

    сбросить() {
        записать(пусто());
    }
};
