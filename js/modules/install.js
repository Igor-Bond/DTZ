/**
 * Установка как приложения: кнопка на главной и пояснение в «Ещё» (Р-17).
 *
 * Кнопка видна, только когда Chrome готов установить: в уже установленном
 * приложении и там, где браузер установку не предлагает, её нет — незачем
 * звать ставить то, что нельзя поставить.
 */

import { ui } from '../core/ui.js';
import { actions } from '../core/actions.js';
import { app } from '../app.js';
import { установка } from '../core/install.js';

/** Кнопка для главной: пусто, если ставить сейчас нечего. */
export function кнопкаУстановки() {
    if (установка.вПриложении || !установка.можно) return '';

    return ui.html`<button class="btn primary install-btn" data-action="установить">Установить как приложение</button>`;
}

/** Раздел «Ещё»: что сейчас думает браузер и что делать. */
export function разделУстановки() {
    if (установка.вПриложении) {
        return ui.html`<p class="muted small" style="margin:18px 2px">Курс открыт как приложение — устанавливать больше ничего не нужно.</p>`;
    }

    if (установка.можно) {
        return ui.html`
            <div class="card" style="margin-top:18px">
                <h2>Установить как приложение</h2>
                <p class="lead">Браузер готов поставить курс: значок появится на рабочем столе или экране телефона, откроется в своём окне и будет работать без сети.</p>
                <button class="btn primary install-btn" data-action="установить">Установить как приложение</button>
            </div>`;
    }

    return ui.html`
        <div class="card" style="margin-top:18px">
            <h2>Установить как приложение</h2>
            <p class="lead">Браузер пока не предложил установку. Кнопка появится здесь и на главной, как только он будет готов, — обычно через несколько секунд после открытия страницы.</p>
            <p class="muted small">Если кнопки нет: в меню браузера (⋮) выберите «Установить приложение» или «Добавить на главный экран». На iPhone: «Поделиться» → «На экран „Домой“». Если меню пишет, что приложение уже установлено, а значка нет, откройте адрес курса заново в новой вкладке и подождите кнопку.</p>
        </div>`;
}

actions.on('установить', async () => {
    await установка.установить();
    app.render(true);
});
