import { describe, it, assert, equal } from '../runner.js';
import { хранилище, ИНТЕРВАЛЫ, ПОСЛЕДНИЙ_ЯЩИК } from '../../js/core/store.js';

const КЛЮЧ = globalThis.__BRIEFE_KEY__;

const чисто = () => { localStorage.removeItem(КЛЮЧ); };

describe('Хранилище: ящики повторения', () => {
    it('тесты работают на своём ключе, а не на настоящем', () => {
        assert(КЛЮЧ === 'briefe.test', `ключ: ${КЛЮЧ}`);
    });

    it('новое упражнение не числится ни в чём', () => {
        чисто();
        equal(хранилище.упражнение('g01-01'), null);
        equal(хранилище.кПовторению(), []);
    });

    it('верный ответ сдвигает ящик, срок растёт', () => {
        чисто();
        const t0 = 1_000_000;
        const у1 = хранилище.записатьОтвет('g01-01', true, 'verb2', t0);
        equal(у1.ящик, 1);
        equal(у1.срок, t0 + ИНТЕРВАЛЫ[1]);

        const у2 = хранилище.записатьОтвет('g01-01', true, 'verb2', t0);
        equal(у2.ящик, 2);
        equal(у2.срок, t0 + ИНТЕРВАЛЫ[2]);
    });

    it('неверный ответ возвращает в нулевой ящик и просит повтор сразу', () => {
        чисто();
        const t0 = 5_000_000;
        хранилище.записатьОтвет('g01-02', true, 'verb2', t0);
        хранилище.записатьОтвет('g01-02', true, 'verb2', t0);
        const у = хранилище.записатьОтвет('g01-02', false, 'verb2', t0);

        equal(у.ящик, 0);
        equal(у.срок, t0);
        assert(хранилище.кПовторению(t0).includes('g01-02'));
    });

    it('ящик не выходит за последний', () => {
        чисто();
        let у;
        for (let i = 0; i < 12; i++) у = хранилище.записатьОтвет('g01-03', true, 'verb2', 1);
        equal(у.ящик, ПОСЛЕДНИЙ_ЯЩИК);
    });

    it('к повторению попадает то, у чего срок вышел', () => {
        чисто();
        const t0 = 10_000_000;
        хранилище.записатьОтвет('g01-04', true, 'verb2', t0);

        equal(хранилище.кПовторению(t0), []);
        equal(хранилище.кПовторению(t0 + ИНТЕРВАЛЫ[1] + 1), ['g01-04']);
    });

    it('освоенным считается верный ответ не с первого раза', () => {
        чисто();
        хранилище.записатьОтвет('g01-05', true, 'verb2', 1);
        assert(!хранилище.освоено('g01-05'));
        хранилище.записатьОтвет('g01-05', true, 'verb2', 1);
        assert(хранилище.освоено('g01-05'));
        хранилище.записатьОтвет('g01-05', false, 'verb2', 1);
        assert(!хранилище.освоено('g01-05'));
    });

    it('ошибки по темам копятся', () => {
        чисто();
        хранилище.записатьОтвет('g01-06', false, 'verb2', 1);
        хранилище.записатьОтвет('g01-07', false, 'verb2', 1);
        хранилище.записатьОтвет('g01-08', true, 'verb2', 1);
        equal(хранилище.всё().темы.verb2, { верно: 1, ошибок: 2 });
    });
});

describe('Хранилище: модули, письма, фразы', () => {
    it('процент раунда только растёт', () => {
        чисто();
        хранилище.записатьРаунд('g01', 70);
        хранилище.записатьРаунд('g01', 40);
        equal(хранилище.модуль('g01').лучший, 70);
        equal(хранилище.модуль('g01').раундов, 2);
    });

    it('теория отмечается', () => {
        чисто();
        assert(!хранилище.модуль('g02').теория);
        хранилище.отметитьТеорию('g02');
        assert(хранилище.модуль('g02').теория);
    });

    it('черновик письма сохраняется, оценка суммируется', () => {
        чисто();
        хранилище.сохранитьЧерновик('s01-a', 'Sehr geehrter Herr Weber');
        equal(хранилище.письмо('s01-a').черновик, 'Sehr geehrter Herr Weber');

        const итог = хранилище.записатьОценкуПисьма('s01-a', { I: 4, II: 4, III: 3, IV: 4 }, 85);
        equal(итог, 15);
        equal(хранилище.письмо('s01-a').итог, 15);
        equal(хранилище.письмо('s01-a').попыток, 1);
        equal(хранилище.письмо('s01-a').черновик, 'Sehr geehrter Herr Weber', 'черновик пережил оценку');
    });

    it('проба сохраняется в истории', () => {
        чисто();
        хранилище.записатьПробу({ задание: 's01-a', слов: 80, итог: 16, оценки: { I: 5 }, минут: 25 });
        equal(хранилище.всё().пробы.length, 1);
        equal(хранилище.всё().пробы[0].итог, 16);
    });

    it('фразы идут по тем же ящикам', () => {
        чисто();
        хранилище.записатьФразу('p01:0', true, 100);
        equal(хранилище.фраза('p01:0').ящик, 1);
        хранилище.записатьФразу('p01:0', false, 100);
        equal(хранилище.фраза('p01:0').ящик, 0);
    });

    it('входной тест записывается', () => {
        чисто();
        хранилище.записатьДиагностику({ модули: { g01: { верно: 3, всего: 4 } }, всего: 4, верно: 3 });
        equal(хранилище.диагностика().модули.g01, { верно: 3, всего: 4 });
    });
});

describe('Хранилище: устойчивость и перенос', () => {
    it('испорченное содержимое заменяется пустым', () => {
        localStorage.setItem(КЛЮЧ, '{не json');
        equal(хранилище.всё().упр, {});

        localStorage.setItem(КЛЮЧ, '[1,2,3]');
        equal(хранилище.всё().упр, {});

        localStorage.setItem(КЛЮЧ, JSON.stringify({ упр: { x: 'строка', y: { ящик: 99, верно: 'abc' } } }));
        const у = хранилище.упражнение('y');
        equal(у.ящик, ПОСЛЕДНИЙ_ЯЩИК);
        equal(у.верно, 0);
        equal(хранилище.упражнение('x'), null);
    });

    it('выгрузка и загрузка возвращают то же самое', () => {
        чисто();
        хранилище.записатьОтвет('g01-01', true, 'verb2', 1);
        хранилище.сохранитьЧерновик('s02-a', 'Liebe Sabine');
        const файл = хранилище.выгрузить();

        чисто();
        equal(хранилище.упражнение('g01-01'), null);

        хранилище.загрузить(файл);
        assert(хранилище.упражнение('g01-01'));
        equal(хранилище.письмо('s02-a').черновик, 'Liebe Sabine');
    });

    it('чужой файл не загружается', () => {
        let текст = '';
        try { хранилище.загрузить('{"что-то":1}'); } catch (e) { текст = e.message; }
        assert(текст.includes('не файл прогресса'), текст);

        текст = '';
        try { хранилище.загрузить('не json'); } catch (e) { текст = e.message; }
        assert(текст.includes('не удалось прочитать'), текст);
    });

    it('сброс стирает всё', () => {
        хранилище.записатьОтвет('g01-01', true, 'verb2', 1);
        хранилище.сбросить();
        equal(хранилище.упражнение('g01-01'), null);
        equal(хранилище.всё().пробы, []);
        чисто();
    });
});
