import { describe, it, assert, equal } from '../runner.js';
import { сессия, выбрать } from '../../js/core/session.js';
import { хранилище } from '../../js/core/store.js';
import { источник, собратьЗанятие } from '../../js/core/sources.js';
import { модульПоId, упражнениеПоId, ГРАММАТИКА } from '../../js/data/catalog.js';

const КЛЮЧ = globalThis.__BRIEFE_KEY__;
const чисто = () => { localStorage.removeItem(КЛЮЧ); сессия.сбросить(); };

const случайное = (() => { let s = 11; return () => (s = (s * 16807) % 2147483647) / 2147483647; })();

const пара = () => [
    { id: 'q-1', type: 'choice', q: 'x', options: ['a', 'b'], answer: 0, explain: 'x', tag: 'verb2' },
    { id: 'q-2', type: 'fix', q: 'x', text: 'Heute ich bin krank.', answer: ['Heute bin ich krank.'], explain: 'x', tag: 'verb2' }
];

describe('Занятие', () => {
    it('ответ не пишется в хранилище, пока не нажато «дальше»', () => {
        чисто();
        сессия.начать('t', 'Тест', пара());
        сессия.ответить(0);
        equal(хранилище.упражнение('q-1'), null);
        сессия.дальше();
        assert(хранилище.упражнение('q-1'));
    });

    it('верный и неверный ответы попадают в итог', () => {
        чисто();
        сессия.начать('t', 'Тест', пара());

        сессия.ответить(0);
        assert(сессия.верноСейчас());
        assert(сессия.дальше());

        сессия.ответить('qqq');
        assert(!сессия.верноСейчас());
        assert(!сессия.дальше(), 'это был последний вопрос');

        const итог = сессия.текущая().итог;
        equal(итог.верных, 1);
        equal(итог.всего, 2);
        equal(итог.процент, 50);
        equal(итог.ошибки, ['q-2']);
        equal(итог.темы.verb2, { верно: 1, ошибок: 1 });
    });

    it('«мой вариант тоже верен» превращает ошибку в верный ответ до записи', () => {
        чисто();
        сессия.начать('t', 'Тест', [пара()[1]]);
        сессия.ответить('Ich bin heute krank.');
        assert(!сессия.верноСейчас());
        сессия.засчитатьМой();
        assert(сессия.верноСейчас());
        сессия.дальше();

        assert(хранилище.упражнение('q-2').последний, 'в хранилище записан верный ответ');
        equal(сессия.текущая().итог.верных, 1);
    });

    it('второй ответ на тот же вопрос не принимается', () => {
        чисто();
        сессия.начать('t', 'Тест', пара());
        сессия.ответить(0);
        const первый = сессия.текущая().результат;
        сессия.ответить(1);
        assert(сессия.текущая().результат === первый);
    });

    it('раунд модуля записывает процент модуля', () => {
        чисто();
        сессия.начать('g01', 'Модуль', пара(), { режим: 'раунд', модуль: 'g01' });
        сессия.ответить(0); сессия.дальше();
        сессия.ответить('Heute bin ich krank.'); сессия.дальше();
        equal(хранилище.модуль('g01').лучший, 100);
    });

    it('входной тест записывает итог по модулям', () => {
        чисто();
        сессия.начать('test', 'Тест', [
            { ...пара()[0], id: 'g01-90' }, { ...пара()[1], id: 'g02-90' }
        ], { режим: 'диагностика' });
        сессия.ответить(0); сессия.дальше();
        сессия.ответить('qqq'); сессия.дальше();

        const д = хранилище.диагностика();
        equal(д.модули.g01, { верно: 1, всего: 1 });
        equal(д.модули.g02, { верно: 0, всего: 1 });
    });

    it('«есть» узнаёт незавершённое занятие по ключу', () => {
        чисто();
        сессия.начать('abc', 'Тест', пара());
        assert(сессия.есть('abc'));
        assert(!сессия.есть('другое'));
    });
});

describe('Выбор упражнений в раунд', () => {
    it('сначала то, что не отвечено, потом то, что ошибочно, потом остальное', () => {
        чисто();
        const список = ['a', 'b', 'c', 'd'].map((с) => ({ id: `s-${с}`, type: 'gap', text: '___', answer: ['x'], q: 'x', explain: 'x', tag: 'verb2' }));

        хранилище.записатьОтвет('s-a', true, 'verb2', 1);
        хранилище.записатьОтвет('s-a', true, 'verb2', 1);
        хранилище.записатьОтвет('s-b', false, 'verb2', 1);

        const взято = выбрать(список, 2, случайное).map((у) => у.id).sort();
        equal(взято, ['s-c', 's-d'], 'новые идут раньше ошибочных и освоенных');

        const три = выбрать(список, 3, случайное).map((у) => у.id);
        assert(три.includes('s-b'), 'ошибочное — следующим после новых');
        assert(!три.includes('s-a'), 'освоенное — последним');
    });

    it('выбор не больше запрошенного и не больше имеющегося', () => {
        чисто();
        const список = [1, 2, 3].map((н) => ({ id: `n-${н}`, type: 'gap', text: '___', answer: ['x'], q: 'x', explain: 'x', tag: 'verb2' }));
        equal(выбрать(список, 10, случайное).length, 3);
        equal(выбрать(список, 2, случайное).length, 2);
    });
});

describe('Источники упражнений', () => {
    it('модуль даёт раунд из десяти', () => {
        чисто();
        const з = собратьЗанятие('g01');
        assert(з, 'модуль g01 не нашёлся');
        equal(з.упражнения.length, 10);
        equal(з.модуль, 'g01');
    });

    it('«all:» даёт все упражнения модуля', () => {
        const з = собратьЗанятие('all:g01');
        equal(з.упражнения.length, модульПоId('g01').exercises.length);
    });

    it('входной тест — по четыре упражнения на модуль грамматики', () => {
        const з = собратьЗанятие('test');
        equal(з.режим, 'диагностика');
        equal(з.упражнения.length, ГРАММАТИКА.length * 4);
    });

    it('«review» пуст, пока нечего повторять, и наполняется после ошибки', () => {
        чисто();
        equal(источник('review'), null);

        хранилище.записатьОтвет('g01-01', false, 'verb2');
        const и = источник('review');
        assert(и && и.упражнения.some((у) => у.id === 'g01-01'));
    });

    it('«mistakes» — то, на чём ошиблись в последний раз', () => {
        чисто();
        хранилище.записатьОтвет('g01-02', false, 'verb2');
        хранилище.записатьОтвет('g01-03', true, 'verb2');
        equal(источник('mistakes').упражнения.map((у) => у.id), ['g01-02']);
    });

    it('«tag:» собирает упражнения по теме', () => {
        const и = источник('tag:verb2');
        assert(и && и.упражнения.length > 5);
        assert(и.упражнения.every((у) => у.tag === 'verb2'));
    });

    it('неизвестный ключ — пусто, а не сбой', () => {
        equal(источник('нет-такого'), null);
        equal(источник(''), null);
        equal(собратьЗанятие('zzz'), null);
    });

    it('упражнение по id находится', () => {
        assert(упражнениеПоId('g01-01'));
        equal(упражнениеПоId('нет'), null);
    });
});
